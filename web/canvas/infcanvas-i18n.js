  /* Resolve an English key to the active language. Both dictionaries are keyed
     by the same English key, so a missing translation is a real bug. */
  function translate(key, params) {
    const k = String(key ?? "");
    const dict = lang.value === "en" ? EN : ZH;
    let out = Object.prototype.hasOwnProperty.call(dict, k) ? dict[k] : k;
    if (!Object.prototype.hasOwnProperty.call(dict, k) && !warned.has(k)) {
      warned.add(k);
      console.warn("[InfCanvas i18n] missing key:", k);
    }
    if (params) {
      for (const name of Object.keys(params)) {
        out = out.split("{" + name + "}").join(String(params[name]));
      }
    }
    return out;
  }
  const warned = new Set();

  /* Old saved data may carry legacy category ids. Normalise to the current
     English key before translating. Mirrors server_routes.CATEGORY_RENAMES. */
  const CATEGORY_ALIASES = {
    "图片生成": "cat.textToImage", "图片编辑": "cat.imageEdit", "图片放大": "cat.imageUpscale",
    "移除背景": "cat.removeBackground", "全能参考": "cat.refToVideo", "参考视频": "cat.refToVideo",
    "首帧": "cat.imageToVideo", "首尾帧": "cat.firstLastFrame", "音乐设计": "cat.textToMusic",
    "音乐翻唱": "cat.musicCover", "语音设计": "cat.textToSpeech", "TTS": "cat.textToSpeech",
    "语音克隆": "cat.voiceClone", "LLM": "cat.llmChat", "LLM对话": "cat.llmChat",
  };
  function normalizeCategory(name) {
    const k = String(name ?? "").trim();
    return CATEGORY_ALIASES[k] || k;
  }
  /* Compact EN labels for workflow categories; falls back to the full EN text. */
  const CAT_SHORT = {
    "cat.textToImage": "T2I", "cat.refToVideo": "R2V", "cat.textToVideo": "T2V",
    "cat.imageToVideo": "I2V", "cat.firstLastFrame": "FLF2V", "cat.textToMusic": "T2M",
    "cat.textToSpeech": "TTS", "cat.voiceClone": "VC", "cat.llmChat": "LLM",
    "cat.speechToText": "STT", "cat.removeBackground": "RMBG", "cat.imageEdit": "Image Edit",
  };
  function cat(name) {
    const key = normalizeCategory(name);
    if (!key) return translate("api.uncategorized");
    return (lang.value === "en" && CAT_SHORT[key]) ? CAT_SHORT[key] : translate(key);
  }

  const listeners = new Set();
  function onChange(cb) {
    listeners.add(cb);
    return () => listeners.delete(cb);
  }

  /* Apply a language without persisting it: ComfyUI's setting is the only
     source of truth, so nothing is ever written back to an independent store. */
  function applyLang(value) {
    if (value === lang.value) return;
    lang.value = value;
    /* Native DOM layers repaint themselves; Vue templates react via the ref. */
    for (const cb of Array.from(listeners)) {
      try { cb(value); } catch (e) { console.warn("[InfCanvas i18n] listener error", e); }
    }
  }

  /* Kept as API for programmatic callers, but it no longer persists a private
     language: the next poll re-aligns to ComfyUI if a caller diverges. */
  function setLang(next) { applyLang(next === "en" ? "en" : "zh"); }
  function toggleLang() { applyLang(lang.value === "zh" ? "en" : "zh"); }
  function current() { return lang.value; }

  /* Follow ComfyUI's `Comfy.Locale` live. The setting resolves asynchronously
     after /api/settings and newer frontends switch it in place without a page
     reload, so poll it (same 500ms cadence as the status bar) and re-align only
     on change. langCode() reads the real setting on every call. */
  setInterval(() => {
    const host = langCode();
    if (host !== lang.value) applyLang(host);
  }, 500);

  NS.i18n = { t: translate, cat, normalizeCategory, catShort: CAT_SHORT, lang, setLang, toggleLang, current, onChange, EN, ZH };
